#!/usr/bin/env node
/*
  Regenerates COLORS.md from the colours actually used in index.html.

    node tools/build-colors.mjs [folder]

  Reads the <style> block (CSS variables in :root, direct hex / rgba() values, and the
  <meta name="theme-color">) and writes one table row per distinct colour.
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const css = html.match(/<style>([\s\S]*?)<\/style>/)[1].replace(/@import\s+url\([^)]*\)\s*;?/g, '');

const COLOR = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/g;
const norm = c => c.replace(/\s+/g, '').toLowerCase();
const vars = new Map();          // --name -> colour
const rows = new Map();          // colour -> { vars:Set, uses:Map(selector -> Set(prop)) }
const row = c => { if (!rows.has(c)) rows.set(c, { vars: new Set(), uses: new Map() }); return rows.get(c); };
const use = (c, sel, prop) => { const r = row(c); if (!r.uses.has(sel)) r.uses.set(sel, new Set()); r.uses.get(sel).add(prop); };

// pass 1: variables
for (const m of css.matchAll(/(--[\w-]+)\s*:\s*([^;}]+)/g)) {
  const c = m[2].match(COLOR);
  if (c) { vars.set(m[1], norm(c[0])); row(norm(c[0])).vars.add(m[1]); }
}
// pass 2: usages inside rules
for (const rule of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
  const sel = rule[1].replace(/\s+/g, ' ').trim();
  if (sel === ':root') continue;
  for (const decl of rule[2].split(';')) {
    const i = decl.indexOf(':');
    if (i < 0) continue;
    const prop = decl.slice(0, i).trim(), value = decl.slice(i + 1);
    for (const v of value.matchAll(/var\((--[\w-]+)\)/g)) if (vars.has(v[1])) use(vars.get(v[1]), sel, prop);
    for (const c of value.match(COLOR) || []) use(norm(c), sel, prop);
  }
}
const theme = html.match(/<meta name="theme-color" content="([^"]+)"/);
if (theme) row(norm(theme[1])).vars.add('meta theme-color');

const describe = r => {
  const parts = [...r.uses].map(([sel, props]) => `\`${sel}\` ${[...props].join(', ')}`);
  const shown = parts.slice(0, 6).join('; ');
  return parts.length > 6 ? `${shown}; …and ${parts.length - 6} more` : shown || '–';
};
const label = r => r.vars.size ? [...r.vars].map(v => `\`${v}\``).join(', ') : 'Direct usage';

// variables first (in file order), then direct colours (in file order)
const ordered = [...rows.entries()].sort((a, b) => (b[1].vars.size > 0) - (a[1].vars.size > 0));
const md = `# Color Palette Used in index.html

Generated by \`tools/build-colors.mjs\` from the CSS in [index.html](index.html) – do not edit by hand.

| Color | CSS variable or direct usage | Where it is used |
| --- | --- | --- |
${ordered.map(([c, r]) => `| \`${c}\` | ${label(r)} | ${describe(r)} |`).join('\n')}
`;
fs.writeFileSync(path.join(ROOT, 'COLORS.md'), md);
console.log(`COLORS.md: ${rows.size} colours`);
